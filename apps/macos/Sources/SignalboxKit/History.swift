import Foundation

// Session history: the stream's "history" line and `signalbox history --json` (HistorySnapshot in
// packages/core/src/types.ts). Each entry is one past or live session: one with a transcript (its title, where it
// ran, what it cost), and, from newer CLIs, one from the Claude app's own session list (the CLI reads the app's
// per-session records read-only, unless run with --no-claude-app). A session in both is one entry with the app's
// title and the transcript's figures; a session only in the app's list has a title, folder and dates but no figures
// and no resume command, because its transcript isn't on this Mac. Titles only: the CLI never sends prompts, message
// bodies or tool output.
// Decoded leniently like the rest of the contract: a missing figure is nil ("unknown"), never 0.

/// Where an entry's title came from. Unknown values from a newer CLI decode as `.unknown`; the title still shows.
public enum HistoryTitleSource: String, LenientStringEnum {
    /// Set with /rename or written by the Claude app (Claude Code's `custom-title` line; the last one wins).
    case custom
    /// Generated by Claude Code (`ai-title`).
    case ai
    /// An agent name (`agent-name`).
    case agentName = "agent-name"
    /// A Codex session name from its session index.
    case index
    /// The Claude app's own title for the session (its session list), which wins over the transcript's.
    case app
    /// No title.
    case none
    case unknown
    public static let fallback: HistoryTitleSource = .unknown

    /// Where the title came from, in the inspector's words; nil when there is no title.
    public var explanation: String? {
        switch self {
        case .custom: "Set with /rename or in the Claude app"
        case .ai: "Generated by Claude Code"
        case .agentName: "Agent name"
        case .index: "Codex session name"
        case .app: "From the Claude app"
        case .none: nil
        case .unknown: "Reported by the CLI"
        }
    }
}

/// How to pick a session up again: the agent's own resume command, run in `cwd`.
public struct HistoryResume: Codable, Hashable, Sendable {
    /// e.g. "claude --resume <id>" or "codex resume <id>", as the CLI sends it.
    public var command: String
    public var cwd: String?

    public init(command: String, cwd: String? = nil) {
        self.command = command
        self.cwd = cwd
    }
}

/// One session in the history list.
public struct SessionHistoryEntry: Codable, Hashable, Sendable, Identifiable {
    public var agent: AgentID
    public var sessionId: String
    /// Sanitized by the CLI (one line, at most 120 characters); `displayTitle` guards again.
    public var title: String?
    public var titleSource: HistoryTitleSource
    /// The Claude app's raw label for how its title was set ("auto": the app generated it), when `titleSource` is
    /// `.app`. A short identifier, shown as given.
    public var appTitleSource: String?
    /// The project directory (the session's working directory).
    public var project: String?
    public var gitBranch: String?
    public var entrypoint: String?
    public var version: String?
    /// First and last line timestamps of the main transcript and its subagent and workflow files.
    public var startedAt: Date
    public var lastActivityAt: Date
    public var durationMs: Double?
    /// Busy, waiting or idle in the fleet when the CLI built the list.
    public var live: Bool
    /// By cost, highest first; a session only in the Claude app's list has the app's model, if it names one.
    public var models: [String]
    /// The effort level the Claude app last set for the session.
    public var effort: String?
    public var responses: Int?
    public var tokens: TokenCounts?
    /// List-price equivalent of the recorded responses (a lower bound).
    public var costUsd: Double?
    public var unpricedTokens: Double?
    /// Share of responses whose usage was a placeholder (streaming not finished when written).
    public var placeholderShare: Double?
    /// Claude Code's own cost-state figure for the session, priced with the same table, when there is one.
    public var ledgerUsd: Double?
    public var compactions: Int?
    public var subagentFiles: Int?
    public var workflowRuns: Int?
    public var resume: HistoryResume?
    public var transcriptPath: String?
    /// The Claude app's own id for the session (its per-session record), when the session is in the app's list.
    public var appSessionId: String?
    /// Archived in the Claude app; nil when the app's list doesn't have the session (or the CLI doesn't say).
    public var archived: Bool?
    /// False for a session that is only in the Claude app's list: its transcript isn't on this Mac (removed, or
    /// created on another machine), so it has no figures and no resume command.
    public var hasTranscript: Bool

    /// The same id as the session's `FleetSession.id`, so a live entry can select it on Sessions.
    public var id: String { "\(agent.rawValue)/\(sessionId)" }

    public init(agent: AgentID, sessionId: String, title: String? = nil, titleSource: HistoryTitleSource? = nil, appTitleSource: String? = nil, project: String? = nil,
                gitBranch: String? = nil, entrypoint: String? = nil, version: String? = nil, startedAt: Date, lastActivityAt: Date,
                durationMs: Double? = nil, live: Bool = false, models: [String] = [], effort: String? = nil, responses: Int? = nil, tokens: TokenCounts? = nil,
                costUsd: Double? = nil, unpricedTokens: Double? = nil, placeholderShare: Double? = nil, ledgerUsd: Double? = nil,
                compactions: Int? = nil, subagentFiles: Int? = nil, workflowRuns: Int? = nil, resume: HistoryResume? = nil,
                transcriptPath: String? = nil, appSessionId: String? = nil, archived: Bool? = nil, hasTranscript: Bool = true) {
        self.agent = agent
        self.sessionId = sessionId
        self.title = title
        self.titleSource = titleSource ?? (title == nil ? .none : .unknown)
        self.appTitleSource = appTitleSource
        self.project = project
        self.gitBranch = gitBranch
        self.entrypoint = entrypoint
        self.version = version
        self.startedAt = startedAt
        self.lastActivityAt = lastActivityAt
        self.durationMs = durationMs
        self.live = live
        self.models = models
        self.effort = effort
        self.responses = responses
        self.tokens = tokens
        self.costUsd = costUsd
        self.unpricedTokens = unpricedTokens
        self.placeholderShare = placeholderShare
        self.ledgerUsd = ledgerUsd
        self.compactions = compactions
        self.subagentFiles = subagentFiles
        self.workflowRuns = workflowRuns
        self.resume = resume
        self.transcriptPath = transcriptPath
        self.appSessionId = appSessionId
        self.archived = archived
        self.hasTranscript = hasTranscript
    }

    enum CodingKeys: String, CodingKey {
        case agent, sessionId, title, titleSource, appTitleSource, project, gitBranch, entrypoint, version, startedAt, lastActivityAt
        case durationMs, live, models, effort, responses, tokens, costUsd, unpricedTokens, placeholderShare, ledgerUsd, compactions
        case subagentFiles, workflowRuns, resume, transcriptPath, appSessionId, archived, hasTranscript
    }

    public init(from decoder: any Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        agent = try c.decode(AgentID.self, forKey: .agent)
        sessionId = try c.decode(String.self, forKey: .sessionId)
        // A row needs a time to sit under a day; either end stands in for the other.
        let started = try? c.decodeIfPresent(Date.self, forKey: .startedAt)
        let last = try? c.decodeIfPresent(Date.self, forKey: .lastActivityAt)
        guard let anchor = last ?? started else {
            throw DecodingError.keyNotFound(CodingKeys.lastActivityAt, .init(codingPath: c.codingPath, debugDescription: "a history entry needs startedAt or lastActivityAt"))
        }
        startedAt = started ?? anchor
        lastActivityAt = last ?? anchor
        title = (try? c.decodeIfPresent(String.self, forKey: .title)).flatMap { $0 }
        let source = (try? c.decodeIfPresent(HistoryTitleSource.self, forKey: .titleSource)).flatMap { $0 }
        titleSource = source ?? (title == nil ? .none : .unknown)
        // Optional extras never cost the row: a wrong type reads as unknown.
        appTitleSource = (try? c.decodeIfPresent(String.self, forKey: .appTitleSource)).flatMap { $0 }
        project = (try? c.decodeIfPresent(String.self, forKey: .project)).flatMap { $0 }
        gitBranch = (try? c.decodeIfPresent(String.self, forKey: .gitBranch)).flatMap { $0 }
        entrypoint = (try? c.decodeIfPresent(String.self, forKey: .entrypoint)).flatMap { $0 }
        version = (try? c.decodeIfPresent(String.self, forKey: .version)).flatMap { $0 }
        // Without a duration, the span between the first and last line stands in, but only when the CLI sent both.
        durationMs = (try? c.decodeIfPresent(Double.self, forKey: .durationMs)).flatMap { $0 }
            ?? started.flatMap { s in last.map { $0.timeIntervalSince(s) * 1000 } }.flatMap { $0 >= 0 ? $0 : nil }
        live = (try? c.decodeIfPresent(Bool.self, forKey: .live)).flatMap { $0 } ?? false
        models = c.lossyArray(String.self, forKey: .models)
        effort = (try? c.decodeIfPresent(String.self, forKey: .effort)).flatMap { $0 }
        responses = (try? c.decodeIfPresent(Int.self, forKey: .responses)).flatMap { $0 }
        tokens = (try? c.decodeIfPresent(TokenCounts.self, forKey: .tokens)).flatMap { $0 }
        costUsd = (try? c.decodeIfPresent(Double.self, forKey: .costUsd)).flatMap { $0 }
        unpricedTokens = (try? c.decodeIfPresent(Double.self, forKey: .unpricedTokens)).flatMap { $0 }
        placeholderShare = (try? c.decodeIfPresent(Double.self, forKey: .placeholderShare)).flatMap { $0 }
        ledgerUsd = (try? c.decodeIfPresent(Double.self, forKey: .ledgerUsd)).flatMap { $0 }
        compactions = (try? c.decodeIfPresent(Int.self, forKey: .compactions)).flatMap { $0 }
        subagentFiles = (try? c.decodeIfPresent(Int.self, forKey: .subagentFiles)).flatMap { $0 }
        workflowRuns = (try? c.decodeIfPresent(Int.self, forKey: .workflowRuns)).flatMap { $0 }
        resume = (try? c.decodeIfPresent(HistoryResume.self, forKey: .resume)).flatMap { $0 }
        transcriptPath = (try? c.decodeIfPresent(String.self, forKey: .transcriptPath)).flatMap { $0 }
        appSessionId = (try? c.decodeIfPresent(String.self, forKey: .appSessionId)).flatMap { $0 }
        archived = (try? c.decodeIfPresent(Bool.self, forKey: .archived)).flatMap { $0 }
        // CLIs from before the Claude app's list sent transcript sessions only. Without the flag, an entry from the
        // app's list with no sign of a transcript (no path, no responses) counts as app-only.
        hasTranscript = (try? c.decodeIfPresent(Bool.self, forKey: .hasTranscript)).flatMap { $0 }
            ?? (appSessionId == nil || transcriptPath != nil || responses != nil)
    }

    /// The longest title shown (the CLI caps titles at 120 characters too).
    public static let maxTitleLength = 120

    /// The title on one line, without control characters or bidi overrides, at most `maxTitleLength` characters;
    /// nil when empty.
    public var displayTitle: String? {
        guard let title else { return nil }
        let cleaned = String(String.UnicodeScalarView(title.unicodeScalars.compactMap { scalar -> Unicode.Scalar? in
            switch scalar.properties.generalCategory {
            case .control, .lineSeparator, .paragraphSeparator: return " "
            default: break
            }
            // Embedding, override and isolate controls could make a title read differently from what it says.
            if (0x202A...0x202E).contains(scalar.value) || (0x2066...0x2069).contains(scalar.value) { return nil }
            return scalar
        }))
        let oneLine = cleaned.split(whereSeparator: \.isWhitespace).joined(separator: " ")
        guard !oneLine.isEmpty else { return nil }
        guard oneLine.count > Self.maxTitleLength else { return oneLine }
        return String(oneLine.prefix(Self.maxTitleLength - 1)) + "…"
    }

    /// The project folder's name, e.g. "api-refactor".
    public var projectName: String? { Fmt.basename(project) }

    /// The model that cost the most (the CLI sorts `models` by cost).
    public var primaryModel: String? { models.first }

    /// `durationMs` in seconds; nil when unknown, and for a session only in the Claude app's list (how long it ran
    /// comes from transcript lines, which aren't on this Mac).
    public var duration: TimeInterval? {
        guard hasTranscript, let durationMs, durationMs.isFinite, durationMs >= 0 else { return nil }
        return durationMs / 1000
    }

    /// True when some tokens are on models with no price row (so `costUsd` is a lower bound).
    public var hasUnpriced: Bool { (unpricedTokens ?? 0) > 0 }

    /// Archived in the Claude app (hidden from History by default, as in the app).
    public var isArchived: Bool { archived == true }

    /// Only in the Claude app's list: no transcript on this Mac, so no figures and no resume command.
    public var isAppOnly: Bool { !hasTranscript }

    /// In the Claude app's session list (with or without a transcript).
    public var isInClaudeApp: Bool { appSessionId != nil }

    /// Where the title came from, in the inspector's words: for the Claude app's title, whether the app generated it
    /// (its raw label "auto"); nil without a title.
    public var titleSourceExplanation: String? {
        guard displayTitle != nil else { return nil }
        if titleSource == .app, appTitleSource == "auto" { return "From the Claude app (generated)" }
        return titleSource.explanation
    }
}

/// What the CLI read for the history: how many transcript sessions, and what it took from the Claude app's list.
public struct HistorySources: Codable, Hashable, Sendable {
    /// Sessions found from transcripts (and Codex rollouts).
    public var transcripts: Int?
    /// The Claude app's session list; nil from CLIs without the reader.
    public var claudeApp: ClaudeAppSource?

    public init(transcripts: Int? = nil, claudeApp: ClaudeAppSource? = nil) {
        self.transcripts = transcripts
        self.claudeApp = claudeApp
    }

    enum CodingKeys: String, CodingKey { case transcripts, claudeApp }

    public init(from decoder: any Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        transcripts = (try? c.decodeIfPresent(Int.self, forKey: .transcripts)).flatMap { $0 }
        claudeApp = (try? c.decodeIfPresent(ClaudeAppSource.self, forKey: .claudeApp)).flatMap { $0 }
    }
}

/// The CLI's reading of the Claude app's session list (read-only; off with `--no-claude-app`).
public struct ClaudeAppSource: Codable, Hashable, Sendable {
    /// Why the CLI didn't read the list.
    public enum OffReason: String, Sendable {
        /// --no-claude-app: the switch in Settings ▸ Advanced.
        case flag
        /// CLAUDE_CONFIG_DIR points away from ~/.claude, whose sessions the app's list describes.
        case claudeConfigDir = "claude-config-dir"
    }

    /// False when the CLI ran with --no-claude-app (Settings ▸ Advanced), or turned the list off itself (`off`).
    public var enabled: Bool
    /// Why it is off, as the CLI sent it ("flag", "claude-config-dir", or a newer reason); nil from older CLIs.
    public var off: String?
    /// The app's session records read.
    public var records: Int?
    /// Records matched to a transcript session (one entry: the app's title, the transcript's figures).
    public var merged: Int?
    /// Records with no transcript on this Mac (entries with no figures).
    public var appOnly: Int?
    /// Records archived in the app.
    public var archived: Int?

    public init(enabled: Bool, off: String? = nil, records: Int? = nil, merged: Int? = nil, appOnly: Int? = nil, archived: Int? = nil) {
        self.enabled = enabled
        self.off = off
        self.records = records
        self.merged = merged
        self.appOnly = appOnly
        self.archived = archived
    }

    enum CodingKeys: String, CodingKey { case enabled, off, records, merged, appOnly, archived }

    public init(from decoder: any Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        records = (try? c.decodeIfPresent(Int.self, forKey: .records)).flatMap { $0 }
        merged = (try? c.decodeIfPresent(Int.self, forKey: .merged)).flatMap { $0 }
        appOnly = (try? c.decodeIfPresent(Int.self, forKey: .appOnly)).flatMap { $0 }
        archived = (try? c.decodeIfPresent(Int.self, forKey: .archived)).flatMap { $0 }
        // A source block without the flag still means the CLI read the list.
        enabled = (try? c.decodeIfPresent(Bool.self, forKey: .enabled)).flatMap { $0 } ?? true
        off = (try? c.decodeIfPresent(String.self, forKey: .off)).flatMap { $0 }
    }

    /// Why the list is off, when it is and the reason is one this app knows. An off list with no reason (older
    /// CLIs) was the Settings switch.
    public var offReason: OffReason? {
        guard !enabled else { return nil }
        guard let off else { return .flag }
        return OffReason(rawValue: off)
    }
}

/// The history list as the CLI sends it, newest `lastActivityAt` first.
public struct HistorySnapshot: Codable, Hashable, Sendable {
    public var v: Int
    public var generatedAt: Date?
    public var entries: [SessionHistoryEntry]
    /// How many sessions matched before the CLI's limit.
    public var total: Int
    /// True when `entries` stops at the CLI's limit.
    public var truncated: Bool
    /// What the CLI read (newer CLIs): transcript sessions and the Claude app's list.
    public var sources: HistorySources?

    public init(v: Int = 1, generatedAt: Date? = nil, entries: [SessionHistoryEntry], total: Int? = nil, truncated: Bool = false,
                sources: HistorySources? = nil) {
        self.v = v
        self.generatedAt = generatedAt
        self.entries = entries
        self.total = total ?? entries.count
        self.truncated = truncated
        self.sources = sources
    }

    enum CodingKeys: String, CodingKey { case v, generatedAt, entries, total, truncated, sources }

    public init(from decoder: any Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        v = (try? c.decodeIfPresent(Int.self, forKey: .v)).flatMap { $0 } ?? 1
        generatedAt = (try? c.decodeIfPresent(Date.self, forKey: .generatedAt)).flatMap { $0 }
        entries = c.lossyArray(SessionHistoryEntry.self, forKey: .entries)
        total = (try? c.decodeIfPresent(Int.self, forKey: .total)).flatMap { $0 } ?? entries.count
        truncated = (try? c.decodeIfPresent(Bool.self, forKey: .truncated)).flatMap { $0 } ?? false
        sources = (try? c.decodeIfPresent(HistorySources.self, forKey: .sources)).flatMap { $0 }
    }

    /// The Claude app's list as the CLI read it, when it read it (nil when it was off or the CLI predates it).
    public var claudeApp: ClaudeAppSource? {
        guard let app = sources?.claudeApp, app.enabled else { return nil }
        return app
    }

    public static func decode(_ data: Data) throws -> HistorySnapshot {
        try SignalboxJSON.decoder().decode(HistorySnapshot.self, from: data)
    }
}
