#!/bin/sh
# Builds apps/macos/build/Signalbox.app: the SwiftUI app with the Bun-compiled `signalbox` CLI inside.
#
#   apps/macos/scripts/build-app.sh            # release build; bundles dist/signalbox, rebuilding it when stale
#   apps/macos/scripts/build-app.sh --debug    # debug build of the app
#   apps/macos/scripts/build-app.sh --no-cli   # app only; run it with SIGNALBOX_CLI=... instead
#   apps/macos/scripts/build-app.sh --install  # also copy the app to ~/Applications/Signalbox.app (opt-in)
#   apps/macos/scripts/build-app.sh --output /tmp/sb   # build into /tmp/sb/Signalbox.app instead of apps/macos/build
#
# Ad-hoc signed (codesign --sign -) for local use. Prints the .app path on success (the installed one with
# --install). Launch at login works best from a stable location such as ~/Applications, not the build folder.
set -eu

here="$(cd "$(dirname "$0")/.." && pwd)"   # apps/macos
repo="$(cd "$here/../.." && pwd)"
config="release"
bundle_cli=1
install=0
out_dir=""

while [ $# -gt 0 ]; do
  case "$1" in
    --debug) config="debug"; shift ;;
    --no-cli) bundle_cli=0; shift ;;
    --install) install=1; shift ;;
    --output)
      [ $# -ge 2 ] || { echo "build-app.sh: --output needs a directory" >&2; exit 2; }
      out_dir="$2"; shift 2 ;;
    -h|--help) sed -n '2,11p' "$0"; exit 0 ;;
    *) echo "build-app.sh: unknown argument: $1" >&2; exit 2 ;;
  esac
done

cli="$repo/dist/signalbox"

# True when dist/signalbox is missing or older than anything that goes into it: sources, price and model
# tables, the command catalogs, the package manifests (the CLI's --version comes from apps/cli/package.json), the
# lockfile and the build script.
cli_is_stale() {
  [ -x "$cli" ] || return 0
  for f in "$repo/package.json" "$repo/bun.lock" "$repo/tsconfig.json" "$repo/scripts/build-cli.sh" \
    "$repo/apps/cli/package.json" "$repo/apps/web/package.json"; do
    [ -f "$f" ] && [ "$f" -nt "$cli" ] && return 0
  done
  newer="$(find "$repo/apps/cli/src" "$repo/apps/web/src" "$repo/packages" "$repo/pricing" "$repo/models" "$repo/catalog" \
    -type f \( -name '*.ts' -o -name '*.tsx' -o -name '*.json' -o -name '*.css' -o -name '*.html' -o -name '*.svg' \) \
    -not -path '*/node_modules/*' -not -path '*/test/*' -not -name '*.test.ts' \
    -newer "$cli" -print 2>/dev/null | head -n 1)"
  [ -n "$newer" ]
}

if [ "$bundle_cli" = 1 ]; then
  if [ -f "$repo/scripts/build-cli.sh" ]; then
    if cli_is_stale; then
      echo "==> Building the signalbox CLI (dist/signalbox is missing or older than its sources)"
      sh "$repo/scripts/build-cli.sh"
    else
      echo "==> dist/signalbox is up to date"
    fi
  elif [ -x "$cli" ]; then
    echo "build-app.sh: scripts/build-cli.sh not found; bundling the existing dist/signalbox" >&2
  else
    echo "build-app.sh: scripts/build-cli.sh not found and no dist/signalbox; building the app WITHOUT the CLI." >&2
    echo "build-app.sh: run it with SIGNALBOX_CLI=bun:$repo/apps/cli/src/main.ts (see apps/macos/README.md)." >&2
    bundle_cli=0
  fi
fi

echo "==> swift build -c $config"
swift build -c "$config" --package-path "$here"
bin_dir="$(swift build -c "$config" --package-path "$here" --show-bin-path)"

app="${out_dir:-$here/build}/Signalbox.app"
rm -rf "$app"
mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources"
cp "$bin_dir/Signalbox" "$app/Contents/MacOS/Signalbox"
chmod 755 "$app/Contents/MacOS/Signalbox"
if [ "$bundle_cli" = 1 ]; then
  cp "$cli" "$app/Contents/Resources/signalbox"
  chmod 755 "$app/Contents/Resources/signalbox"
fi
# The icon is generated by scripts/make-icon.swift and committed; regenerate it only when the drawing changes.
icon="$here/Resources/AppIcon.icns"
if [ -f "$icon" ]; then
  cp "$icon" "$app/Contents/Resources/AppIcon.icns"
else
  echo "build-app.sh: $icon not found; run: swift apps/macos/scripts/make-icon.swift" >&2
fi

cat > "$app/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleIdentifier</key>
  <string>dev.signalbox.app</string>
  <key>CFBundleName</key>
  <string>Signalbox</string>
  <key>CFBundleDisplayName</key>
  <string>Signalbox</string>
  <key>CFBundleExecutable</key>
  <string>Signalbox</string>
  <key>CFBundleIconFile</key>
  <string>AppIcon</string>
  <key>CFBundlePackageType</key>
  <string>APPL</string>
  <key>CFBundleShortVersionString</key>
  <string>0.1.0</string>
  <key>CFBundleVersion</key>
  <string>1</string>
  <key>CFBundleInfoDictionaryVersion</key>
  <string>6.0</string>
  <key>LSMinimumSystemVersion</key>
  <string>14.0</string>
  <key>LSApplicationCategoryType</key>
  <string>public.app-category.developer-tools</string>
  <key>NSHumanReadableCopyright</key>
  <string>Unofficial. Not affiliated with Anthropic, OpenAI or Google.</string>
  <key>NSHighResolutionCapable</key>
  <true/>
  <key>NSPrincipalClass</key>
  <string>NSApplication</string>
</dict>
</plist>
PLIST
printf 'APPL????' > "$app/Contents/PkgInfo"
# The bundle version follows VERSION at the repo root (packaging/version.sh keeps every copy in step).
if [ -f "$repo/VERSION" ]; then
  bundle_version="$(tr -d ' \t\r\n' < "$repo/VERSION")"
  if printf '%s\n' "$bundle_version" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+$'; then
    /usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString $bundle_version" "$app/Contents/Info.plist"
  else
    echo "build-app.sh: VERSION holds '$bundle_version', expected X.Y.Z; keeping 0.1.0" >&2
  fi
fi

# macOS 26 draws icons from Icon Composer files (glass, light and dark, tinted). Compile Resources/AppIcon.icon into
# Assets.car and name it in CFBundleIconName; AppIcon.icns stays as CFBundleIconFile for anything that can't use it.
composer="$here/Resources/AppIcon.icon"
if [ -d "$composer" ]; then
  icon_tmp="$(mktemp -d "${TMPDIR:-/tmp}/signalbox-icon.XXXXXX")"
  if xcrun actool "$composer" --compile "$icon_tmp" --platform macosx --minimum-deployment-target 14.0 \
      --app-icon AppIcon --output-partial-info-plist "$icon_tmp/partial.plist" --target-device mac >"$icon_tmp/actool.log" 2>&1 \
    && [ -f "$icon_tmp/Assets.car" ]; then
    cp "$icon_tmp/Assets.car" "$app/Contents/Resources/Assets.car"
    /usr/libexec/PlistBuddy -c 'Add :CFBundleIconName string AppIcon' "$app/Contents/Info.plist"
    echo "==> Compiled the Icon Composer icon (Assets.car)"
  else
    echo "build-app.sh: actool couldn't compile $composer; using AppIcon.icns only (see $icon_tmp/actool.log)" >&2
  fi
  [ -f "$app/Contents/Resources/Assets.car" ] && rm -rf "$icon_tmp"
fi

echo "==> Signing (ad-hoc)"
if [ "$bundle_cli" = 1 ]; then
  codesign --force --sign - "$app/Contents/Resources/signalbox"
fi
codesign --force --sign - "$app"
codesign --verify --strict "$app"

if [ "$bundle_cli" = 1 ]; then
  version="$("$app/Contents/Resources/signalbox" --version 2>/dev/null || true)"
  echo "==> Bundled CLI: signalbox ${version:-(did not report a version)}"
else
  echo "==> No CLI bundled"
fi

if [ "$install" = 1 ]; then
  dest_dir="$HOME/Applications"
  dest="$dest_dir/Signalbox.app"
  # A running copy keeps its old code until it quits; say so rather than touching the process.
  if pgrep -f "$dest/Contents/MacOS/Signalbox" >/dev/null 2>&1; then
    echo "build-app.sh: Signalbox is running from $dest; quit it before installing (nothing was copied)." >&2
    exit 1
  fi
  echo "==> Installing to $dest"
  mkdir -p "$dest_dir"
  rm -rf "$dest"
  ditto "$app" "$dest"
  codesign --verify --strict "$dest"
  echo "$dest"
  exit 0
fi
echo "$app"
